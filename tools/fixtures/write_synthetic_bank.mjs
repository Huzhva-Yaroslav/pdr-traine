function textQuestions(ticket) {
  return textBank.slice(0, 12).map((group, groupIndex) => {
    const variant = group[(ticket - 1) % group.length]
    if (!variant) throw new Error(`missing variant ${ticket} ${groupIndex}`)
    const [topicId, text, options, correctIndex, explanation, rulesRef] = variant
    return question(
      `t${ticket}q${groupIndex + 9}`,
      String(ticket),
      topicId,
      text,
      options,
      correctIndex,
      explanation,
      rulesRef,
    )
  })
}

const selfCheck = passOrder([
  { from: 'w', label: 'А', turn: 'straight' },
  { from: 's', label: 'Б', turn: 'straight' },
])
if (selfCheck?.map((car) => car.label).join() !== 'Б,А') {
  throw new Error(`solver self-check failed: ${selfCheck?.map((car) => car.label).join()}`)
}

const questions = []
for (let ticket = 1; ticket <= 6; ticket += 1) {
  questions.push(...sceneSet(ticket), ...textQuestions(ticket))
}

const seenText = new Set()
for (const item of questions) {
  if (seenText.has(item.text)) throw new Error(`duplicate text ${item.id}`)
  seenText.add(item.text)
  if (item.answers.length < 2 || item.answers.length > 5) throw new Error(`answers ${item.id}`)
}
const byTicket = new Map()
for (const item of questions) byTicket.set(item.ticketId, (byTicket.get(item.ticketId) ?? 0) + 1)
for (const [ticketId, count] of byTicket) {
  if (count !== 20) throw new Error(`ticket ${ticketId} has ${count}`)
}

