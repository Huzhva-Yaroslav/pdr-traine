const opposite = { n: 's', s: 'n', e: 'w', w: 'e' }
const rightOf = { n: 'e', e: 's', s: 'w', w: 'n' }

function blockedBy(car, waiting) {
  if (!car.main && waiting.some((other) => other !== car && other.main)) {
    return waiting.find((other) => other.main) ?? null
  }
  const peers = waiting.filter((other) => other !== car && Boolean(other.main) === Boolean(car.main))
  if (car.turn === 'left') {
    const headOn = peers.find((other) => other.from === opposite[car.from] && other.turn !== 'left')
    if (headOn) return headOn
  }
  const travel = opposite[car.from]
  const threatFrom = rightOf[travel]
  return peers.find((other) => other.from === threatFrom) ?? null
}

function passOrder(cars) {
  const waiting = [...cars]
  const done = []
  while (waiting.length > 0) {
    const ready = waiting.filter((car) => !blockedBy(car, waiting))
    if (ready.length === 0) return null
    ready.sort((left, right) => left.label.localeCompare(right.label, 'uk'))
    const next = ready[0]
    if (!next) return null
    done.push(next)
    waiting.splice(waiting.indexOf(next), 1)
  }
  return done
}

function sceneSvg(spec) {
  const cars = (spec.cars ?? [])
    .map((car) => {
      const spot = {
        s: [332, 400, 'n'],
        n: [388, 78, 's'],
        w: [78, 214, 'e'],
        e: [642, 266, 'w'],
      }[car.from]
      if (!spot) return ''
      const [x, y, dir] = spot
      const rotate = { n: -90, e: 0, s: 90, w: 180 }[dir]
      const turnMark = car.turn === 'left' ? '↰' : car.turn === 'right' ? '↱' : '↑'
      return `
        <g transform="translate(${x} ${y}) rotate(${rotate})">
          <rect x="-36" y="-16" width="62" height="32" rx="7" fill="${car.main ? '#b45309' : '#0f766e'}" stroke="#082f2a" stroke-width="2"/>
          <polygon points="26,-8 40,0 26,8" fill="#082f2a"/>
        </g>
        <text x="${x}" y="${y + 5}" text-anchor="middle" font-size="16" font-family="sans-serif" font-weight="700" fill="#ffffff">${car.label}</text>
        <text x="${x}" y="${y + 28}" text-anchor="middle" font-size="16" font-family="sans-serif" fill="#0f172a">${turnMark}</text>`
    })
    .join('')

  const signs = (spec.signs ?? [])
    .map((sign) => {
      const spot = { s: [250, 360], n: [470, 110], w: [150, 150], e: [560, 330] }[sign.from]
      if (!spot) return ''
      const [x, y] = spot
      if (sign.kind === 'main') {
        return `<rect x="${x - 16}" y="${y - 16}" width="32" height="32" transform="rotate(45 ${x} ${y})" fill="#facc15" stroke="#1f2937" stroke-width="2"/>`
      }
      if (sign.kind === 'yield') {
        return `<polygon points="${x},${y + 18} ${x - 18},${y - 14} ${x + 18},${y - 14}" fill="#ffffff" stroke="#b91c1c" stroke-width="4"/>`
      }
      if (sign.kind === 'stop') {
        return `<rect x="${x - 18}" y="${y - 18}" width="36" height="36" rx="4" fill="#b91c1c"/><text x="${x}" y="${y + 5}" text-anchor="middle" font-size="11" font-family="sans-serif" fill="#ffffff">STOP</text>`
      }
      return ''
    })
    .join('')

  const lights = (spec.lights ?? [])
    .map((light) => {
      const spot = { s: [430, 330], n: [290, 140], w: [250, 300], e: [470, 170] }[light.from]
      if (!spot) return ''
      const [x, y] = spot
      const color = { red: '#dc2626', yellow: '#eab308', green: '#16a34a' }[light.color]
      return `
        <rect x="${x}" y="${y}" width="22" height="58" rx="4" fill="#111827"/>
        <circle cx="${x + 11}" cy="${y + 12}" r="6" fill="${light.color === 'red' ? color : '#374151'}"/>
        <circle cx="${x + 11}" cy="${y + 29}" r="6" fill="${light.color === 'yellow' ? color : '#374151'}"/>
        <circle cx="${x + 11}" cy="${y + 46}" r="6" fill="${light.color === 'green' ? color : '#374151'}"/>`
    })
    .join('')

  const people = (spec.people ?? [])
    .map((person, index) => {
      const x = 470 + index * 28
      const y = 210
      return `
        <circle cx="${x}" cy="${y}" r="8" fill="#1d4ed8"/>
        <line x1="${x}" y1="${y + 8}" x2="${x}" y2="${y + 28}" stroke="#1d4ed8" stroke-width="3"/>
        <text x="${x}" y="${y - 12}" text-anchor="middle" font-size="12" font-family="sans-serif">${person.label}</text>`
    })
    .join('')

  const zebra = spec.people?.length
    ? '<g stroke="#f8fafc" stroke-width="4"><line x1="430" y1="180" x2="430" y2="300"/><line x1="448" y1="180" x2="448" y2="300"/><line x1="466" y1="180" x2="466" y2="300"/><line x1="484" y1="180" x2="484" y2="300"/><line x1="502" y1="180" x2="502" y2="300"/></g>'
    : ''

  const extra =
    spec.layout === 'round'
      ? '<circle cx="360" cy="240" r="70" fill="none" stroke="#f8fafc" stroke-width="18"/><circle cx="360" cy="240" r="28" fill="#86efac" stroke="#166534"/>'
      : spec.layout === 'narrow'
        ? '<rect x="300" y="150" width="70" height="40" fill="#f97316" stroke="#7c2d12"/><text x="335" y="175" text-anchor="middle" font-size="12" font-family="sans-serif">ремонт</text>'
        : spec.layout === 'solid'
          ? '<line x1="40" y1="240" x2="680" y2="240" stroke="#f8fafc" stroke-width="4"/>'
          : spec.layout === 'dashed'
            ? '<line x1="40" y1="240" x2="680" y2="240" stroke="#f8fafc" stroke-width="4" stroke-dasharray="18 14"/>'
            : ''

  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 720 480" width="720" height="480">
  <rect width="720" height="480" fill="#dbe4ee"/>
  <rect x="0" y="180" width="720" height="120" fill="#4b5563"/>
  <rect x="300" y="0" width="120" height="480" fill="#4b5563"/>
  <text x="24" y="32" font-size="16" font-family="sans-serif" fill="#0f172a">${spec.caption}</text>
  ${extra}
  ${zebra}
  ${signs}
  ${lights}
  ${cars}
  ${people}
</svg>`
}

function question(id, ticketId, topicId, text, options, correctIndex, explanation, rulesRef, imageBody) {
  const answers = options.map((textValue, index) => ({
    id: `${id}-a${index + 1}`,
    text: textValue,
  }))
  const correct = answers[correctIndex]
  if (!correct) throw new Error(`bad correct index for ${id}`)
  return {
    id,
    ticketId,
    topicId,
    categories: ['B'],
    text,
    answers,
    correctAnswerId: correct.id,
    explanation,
    rulesRef,
    ...(imageBody ? { images: [`images/${id}.svg`] } : {}),
    imageBody,
  }
}

function orderQuestion(ticket, index, cars, caption, explanation) {
  const order = passOrder(cars)
  if (!order) throw new Error(`deadlock ticket ${ticket} scene ${index}`)
  const labels = order.map((car) => car.label).join(' → ')
  const wrong = [...order].reverse().map((car) => car.label).join(' → ')
  const onlyFirst = order[0]?.label ?? ''
  const options = [
    labels,
    wrong,
    `спершу ${onlyFirst === 'А' ? 'Б' : 'А'}, решта одночасно`,
    'усі проїжджають одночасно',
  ]
  return question(
    `t${ticket}s${index}`,
    String(ticket),
    'priority',
    `${caption}. У якій послідовності проїдуть автомобілі?`,
    options,
    0,
    `${explanation} Порядок: ${labels}.`,
    'п. 16.11–16.14 ПДР',
    sceneSvg({ cars, signs: cars.filter((car) => car.main).map((car) => ({ from: car.from, kind: 'main' })), caption }),
  )
}

